"""Render an :class:`EvalResult` as JSON and Markdown.

Both outputs are deterministic: no timestamps, no timings, sorted keys, fixed float rounding and
``\\n`` line endings. Running the same command twice, on any platform, writes identical bytes;
CI checks this by regenerating the committed report and diffing it.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Any

from retrievallab.evaluate import COMPARED_METRICS, METRICS, EvalResult
from retrievallab.metrics import Interval

COMMAND = "uv run retrievallab eval"


def _r(x: float) -> float:
    return round(x, 6)


def _interval(iv: Interval) -> dict[str, float]:
    return {"mean": _r(iv.mean), "low": _r(iv.low), "high": _r(iv.high)}


def to_json(result: EvalResult) -> dict[str, Any]:
    cfg = result.config
    return {
        "command": COMMAND,
        "config": {
            "corpus_dir": cfg.corpus_dir.as_posix(),
            "queries_path": cfg.queries_path.as_posix(),
            "methods": list(cfg.methods),
            "chunkers": list(cfg.chunkers),
            "baseline": cfg.baseline,
            "depth": cfg.depth,
            "bootstrap": {
                "n_resamples": cfg.n_resamples,
                "confidence": cfg.confidence,
                "seed": cfg.seed,
            },
            "include_boilerplate": cfg.include_boilerplate,
        },
        "data": {
            "documents": result.n_documents,
            "queries": result.n_queries,
            "labelled_passages": result.n_labels,
            "corpus_manifest_sha256": result.corpus_sha256,
            "queries_sha256": result.queries_sha256,
        },
        "runs": [
            {
                "run": run.run_id,
                "method": run.method,
                "chunker": run.chunker,
                "chunks_indexed": run.n_chunks,
                "summary": {name: _interval(iv) for name, iv in run.summary.items()},
                "per_query": {
                    qid: {
                        "metrics": {k: _r(v) for k, v in scores.items()},
                        "top": [asdict(c) for c in run.top[qid]],
                    }
                    for qid, scores in run.per_query.items()
                },
            }
            for run in result.runs
        ],
        "comparisons": [
            {
                "run": c.run_id,
                "baseline": c.baseline,
                "metric": c.metric,
                "delta": _interval(c.delta),
                "verdict": c.verdict,
            }
            for c in result.comparisons
        ],
    }


def _fmt(iv: Interval) -> str:
    return f"{iv.mean:.3f} [{iv.low:.3f}, {iv.high:.3f}]"


def _signed(iv: Interval) -> str:
    return f"{iv.mean:+.3f} [{iv.low:+.3f}, {iv.high:+.3f}]"


def results_table(result: EvalResult) -> str:
    """The summary table quoted in the README."""
    lines = [
        "| Run | Chunks | nDCG@10 | MRR@10 | Recall@10 | Recall@5 | P@5 |",
        "| --- | ---: | --- | --- | --- | ---: | ---: |",
    ]
    for run in result.runs:
        s = run.summary
        lines.append(
            f"| {run.run_id} | {run.n_chunks} | {_fmt(s['ndcg@10'])} | {_fmt(s['mrr@10'])} "
            f"| {_fmt(s['recall@10'])} | {s['recall@5'].mean:.3f} | {s['precision@5'].mean:.3f} |"
        )
    return "\n".join(lines)


def comparison_table(result: EvalResult) -> str:
    lines = [
        "| Run vs " + result.config.baseline + " | Metric | Difference [95% CI] | Verdict |",
        "| --- | --- | --- | --- |",
    ]
    for c in result.comparisons:
        lines.append(f"| {c.run_id} | {c.metric} | {_signed(c.delta)} | {c.verdict} |")
    return "\n".join(lines)


def to_markdown(result: EvalResult) -> str:
    cfg = result.config
    pct = round(cfg.confidence * 100)
    missed = [
        qid
        for qid in result.runs[0].per_query
        if all(run.per_query[qid]["recall@10"] == 0.0 for run in result.runs)
    ]
    parts = [
        "# Retrieval evaluation report",
        "",
        f"Generated by `{COMMAND}`. Regenerate it with the same command; the output is "
        "deterministic.",
        "",
        f"- Corpus: {result.n_documents} documents (`{cfg.corpus_dir.as_posix()}`, manifest "
        f"SHA-256 `{result.corpus_sha256[:16]}...`)",
        f"- Queries: {result.n_queries} with {result.n_labels} graded passage labels "
        f"(`{cfg.queries_path.as_posix()}`, SHA-256 `{result.queries_sha256[:16]}...`)",
        f"- Retrieval depth: top {cfg.depth} chunks per query, mapped to passages (RFC sections)",
        f"- Boilerplate sections indexed: {'yes' if cfg.include_boilerplate else 'no'}",
        f"- Intervals: {pct}% percentile bootstrap over queries, {cfg.n_resamples} resamples, "
        f"seed {cfg.seed}",
        "",
        "## Results",
        "",
        f"Mean over queries with {pct}% confidence interval.",
        "",
        results_table(result),
        "",
        "## Comparisons with the baseline",
        "",
        f"Paired bootstrap of the per-query difference (run minus `{cfg.baseline}`). "
        '"better" or "worse" only when the interval excludes zero. These are '
        f"{len(result.comparisons)} comparisons on one query set with no multiple-comparison "
        "correction, so treat a borderline interval as weak evidence.",
        "",
        comparison_table(result),
        "",
        "## Queries no run answered",
        "",
        "Queries where every run has Recall@10 = 0:",
        "",
        (", ".join(f"`{q}`" for q in missed) if missed else "none"),
        "",
        "## Metric definitions",
        "",
        "- nDCG@10: exponential gain `2^grade - 1`, log2 discount, ideal ranking from all labels.",
        "- MRR@10: reciprocal rank of the first relevant passage in the top 10, else 0.",
        "- Recall@k: share of labelled passages in the top k. P@5: relevant passages in the top 5"
        " divided by 5.",
        f"- Reported metrics: {', '.join(METRICS)}; compared metrics: "
        f"{', '.join(COMPARED_METRICS)}.",
        "",
    ]
    return "\n".join(parts)


def write_reports(result: EvalResult, out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "eval.json"
    md_path = out_dir / "eval.md"
    json_path.write_text(
        json.dumps(to_json(result), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    md_path.write_text(to_markdown(result), encoding="utf-8", newline="\n")
    return md_path, json_path
